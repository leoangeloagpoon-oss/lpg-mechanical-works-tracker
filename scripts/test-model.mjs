import assert from 'node:assert/strict';
import {activitySchema,projectSchema,inspectionSchema,actionSchema,progress,projectProgress,overdue} from '../app/model.ts';
const a={projectId:'p',name:'Piping',area:'Tank yard',responsible:'Engineer',start:'2026-10-01',end:'2026-10-20',status:'In progress',mode:'quantity',unit:'m',planned:200,completed:50,percent:0,notes:''};
assert.equal(progress(a),25);
assert.equal(progress({...a,mode:'manual',percent:80}),80);
assert.equal(projectProgress([]),null);
assert.equal(projectProgress([a,{...a,mode:'manual',percent:75}]),50);
assert.equal(overdue(a,'2026-10-26'),true);
assert.equal(overdue({...a,completed:200},'2026-10-26'),false);
assert.equal(overdue({...a,end:'2026-10-26'},'2026-10-26'),false);
for(const bad of [{completed:201},{planned:0},{completed:-1},{unit:''},{status:'Complete'},{start:'2026-10-30'},{start:'2026-02-30'},{mode:'manual',percent:101}]) assert.equal(activitySchema.safeParse({...a,...bad}).success,false,JSON.stringify(bad));
assert.equal(activitySchema.safeParse(a).success,true);
assert.equal(activitySchema.safeParse({...a,completed:200,status:'Complete'}).success,true);
assert.equal(projectSchema.safeParse({name:'Test',location:'',contractor:'',start:'2026-11-01',end:'2026-10-01',areas:[]}).success,false);
const i={projectId:'p',activityId:'a',reference:'WIR-01',requested:'2026-10-20',inspected:'2026-10-21',inspector:'Engineer',result:'Failed',comments:'Issue'};
assert.equal(inspectionSchema.safeParse(i).success,true);
assert.equal(inspectionSchema.safeParse({...i,inspected:''}).success,false);
assert.equal(inspectionSchema.safeParse({...i,inspected:'2026-10-19'}).success,false);
assert.equal(inspectionSchema.safeParse({...i,inspector:''}).success,false);
assert.equal(actionSchema.safeParse({projectId:'p',inspectionId:'i',title:'Repair',responsible:'Engineer',due:'2026-10-28',status:'Open',notes:''}).success,true);
console.log('PASS: progress, averages, overdue dates, date ranges, quantities, inspection outcomes, corrective actions.');
